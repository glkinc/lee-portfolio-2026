/**
 * Case study content (copy from the Figma "case study / *" frames).
 *
 * IMAGES: final imagery isn't ready yet, so every image has `src: undefined`
 * and renders as a token-styled placeholder with a Bauhaus tile. Drop a
 * PNG/JPG into /public/images/case-studies/<slug>/ and set `src` (keep the
 * width/height and alt text accurate) to replace a placeholder.
 */
export interface CaseImage {
  /** Render at the image's own aspect ratio instead of cropping to the section's frame (for screenshots). */
  natural?: boolean;
  /** Draw a hairline border (for screenshots that sit white on white). */
  bordered?: boolean;
  /** Still version of an animated `src`, shown when the visitor prefers reduced motion. */
  staticSrc?: string;
  /** Tailwind background class for the tile behind a pictograph (layout "pictographs"). */
  bg?: string;
  /** Cap the rendered width in px (for tall device screens), centred in its cell. */
  displayWidth?: number;
  src?: string;
  alt: string;
  width: number;
  height: number;
  /** Shown on the placeholder until `src` is set: what image to add, and a simpler option if the ideal can't be shared. */
  note?: { ideal: string; fallback: string };
  /** Tile shown while the image is a placeholder. */
  tile: TileSpec;
  /**
   * Animated SVG thumbnail, generated from src/assets/thumbs/<slug>-thumb.svg
   * by `npm run thumbs`. Plays forward while the card's image or CTA is
   * hovered, backward on leave.
   */
  animated?: {
    markup: string;
    background: string;
    /** Playback speed multiplier (default 1; 0.5 = twice as slow). */ speed?: number;
  };
}

export interface CaseStudy {
  slug: string;
  number: string;
  category: string;
  /** Icon shown in the category pill (an SVG, tinted by the text colour). */
  icon: string;
  name: string;
  /** Logo shown in the overlay's sticky header and "next case study" block. */
  logo: {
    src: string;
    alt: string;
    width: number;
    height: number;
    /** Tailwind height classes for the overlay's sticky header (default "h-8 lg:h-10"). */
    headerClass?: string;
    /** Tailwind height classes in the "next case study" block (default "h-12 lg:h-16"). */
    nextClass?: string;
  };
  /** Card summary on the home page. */
  summary: string;
  cardSkills: string[];
  cta: string;
  thumb: CaseImage;
  title: string;
  intro: string;
  meta: { label: string; value: string }[];
  heroImage: CaseImage;
  /** Optional external link shown under the intro (opens in a new tab). */
  link?: { href: string; label: string };
  /** Draw a hairline border around the case study's images (for white-on-white screenshots). */
  imageBorder?: boolean;
  highlights: { title: string; body: string }[];
  overview: { challenge: string; role: string };
  approach: {
    intro: string;
    steps: { title: string; body: string }[];
    images?: [CaseImage, CaseImage];
  };
  features: {
    title: string;
    body: string;
    image: CaseImage;
    /** Several images instead of one. `grid` = two columns, `stack` = full-width one under another, `narrow` = one centred, ~720px, `cards` = a responsive 2 / 3 / 4-column card grid. */
    gallery?: CaseImage[];
    /** Optional external link shown under the body (opens in a new tab). */
    link?: { href: string; label: string };
    layout?:
      "grid" | "stack" | "narrow" | "cards" | "pair" | "sidecar" | "trio" | "pictographs";
  }[];
  skills: string[];
  outcome: string;
  seo: { title: string; description: string };
}

